// Partial Fisher–Yates: no duplicate examples and no mutation of the shared bank.
// Select once per request, outside provider/model retries.
export function selectVoiceAnalysisStyleExamples(random: () => number = Math.random) {
  const pool = [...VOICE_ANALYSIS_STYLE_EXAMPLES];
  for (let index = 0; index < VOICE_ANALYSIS_STYLE_SAMPLE_COUNT; index++) {
    const pick = index + Math.floor(random() * (pool.length - index));
    [pool[index], pool[pick]] = [pool[pick], pool[index]];
  }
  return pool.slice(0, VOICE_ANALYSIS_STYLE_SAMPLE_COUNT);
}

